#!/usr/bin/env python3
"""Compile the common-password list into the daemon (daemon/pwpolicy.h).

    scripts/build/pw_common.py OUT.c third_party/pwlist/common.txt

Writes `const char *const oc_pw_common[]`, sorted bytewise for a binary search,
and `const size_t oc_pw_common_n`. Each line is already lowercased.
"""
import sys

def main(argv):
    if len(argv) != 3:
        sys.stderr.write("usage: scripts/build/pw_common.py OUT.c LIST\n")
        return 2
    words = sorted({w.rstrip("\r\n") for w in open(argv[2], encoding="ascii") if w.strip()},
                   key=lambda w: w.encode())
    out = ["/* Generated by scripts/build/pw_common.py -- do not edit. */\n#include <stddef.h>\n",
           "const char *const oc_pw_common[] = {\n"]
    for w in words:
        out.append('    "' + w.replace("\\", "\\\\").replace('"', '\\"').replace("?", "\\?") + '",\n')
    out.append("};\nconst size_t oc_pw_common_n = %d;\n" % len(words))
    open(argv[1], "w").write("".join(out))
    return 0

if __name__ == "__main__":
    sys.exit(main(sys.argv))
